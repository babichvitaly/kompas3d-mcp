"""Offline authoring boundary contracts, not native executors."""

from typing import Annotated, Literal

from pydantic import Field, StrictBool, ValidationError

from .state_oracles import Evidence, Key, NonnegativeInt, PositiveInt, _result
from .view_state import Finite, Sha256, ViewState


class OccurrenceKey(Evidence):
    path: Annotated[list[NonnegativeInt], Field(min_length=1)]
    source: Key
    source_sha256: Sha256
    matrix: Annotated[list[Finite], Field(min_length=16, max_length=16)]


class FreshOccurrence(Evidence):
    key: OccurrenceKey
    reference: Key
    epoch: NonnegativeInt


class BindingEvidence(Evidence):
    expected: OccurrenceKey
    boundary_kind: Literal['row_add', 'description_add', 'tuning_update']
    boundary_epoch: NonnegativeInt
    after_boundary: FreshOccurrence
    include_epoch: NonnegativeInt
    include_return: StrictBool
    row_update_epoch: NonnegativeInt
    after_row_update: FreshOccurrence
    geometry_read_epoch: NonnegativeInt
    geometry_references: list[Key]


def assess_occurrence_binding(payload):
    try:
        e = BindingEvidence.model_validate(payload)
        if not (e.boundary_epoch < e.after_boundary.epoch < e.include_epoch
                < e.row_update_epoch < e.after_row_update.epoch < e.geometry_read_epoch):
            raise ValueError('Lookup must be fresh after each native mutation boundary')
        if e.after_boundary.key != e.expected or e.after_row_update.key != e.expected:
            raise ValueError('Occurrence path/source/matrix selection differs')
        if not e.include_return or e.geometry_references != [e.after_row_update.reference]:
            raise ValueError('IncludeGeometry is not exact post-Update fresh occurrence binding')
    except (ValueError, ValidationError) as exc:
        return _result([str(exc)])
    return _result([])


class NativeRow(Evidence):
    uuid: Key
    section: PositiveInt
    columns: dict[Key, str]
    sync: StrictBool
    edit_source: StrictBool


class RowEvidence(Evidence):
    policy: Literal['preserve_autogenerated_true']
    autogenerated: StrictBool
    attempted_sync_value: StrictBool | None = None  # diagnostic of a legacy ignored setter
    expected: NativeRow
    immediate: NativeRow
    after_row_update: NativeRow
    after_description_update: NativeRow
    saved_ro: Annotated[list[NativeRow], Field(min_length=2, max_length=2)]


def assess_autogenerated_row(payload):
    try:
        e = RowEvidence.model_validate(payload)
        if not e.autogenerated or not e.expected.sync or e.expected.edit_source or not e.expected.columns:
            raise ValueError('Autogenerated policy requires sync=True, EditSourceObject=False and payload')
        if any(row != e.expected for row in [e.immediate, e.after_row_update,
                                            e.after_description_update, *e.saved_ro]):
            raise ValueError('Native UUID/section/text/sync payload readback differs')
    except (ValueError, ValidationError) as exc:
        return _result([str(exc)])
    return {**_result([]), 'ignored_disable_setter': e.attempted_sync_value is False}


class MaterialEnvelope(Evidence):
    bounds: Annotated[list[Finite], Field(min_length=4, max_length=4)]
    geometry_digest: Sha256


class BoundsCycle(Evidence):
    open_id: Key
    read_only: StrictBool
    epoch: NonnegativeInt
    drawing_sha256: Sha256
    state: ViewState


class BoundsEvidence(Evidence):
    before_annotations: ViewState
    material_before: MaterialEnvelope
    material_after: MaterialEnvelope
    anchor_bounds: Annotated[list[Finite], Field(min_length=4, max_length=4)]
    writeback_complete_epoch: NonnegativeInt
    final_recapture_epoch: NonnegativeInt
    final_whole: ViewState
    sealed_drawing_sha256: Sha256
    saved_ro: Annotated[list[BoundsCycle], Field(min_length=2, max_length=2)]


def assess_annotation_bounds(payload):
    try:
        e = BoundsEvidence.model_validate(payload)
        b = e.material_before.bounds
        if b[2] <= b[0] or b[3] <= b[1]:
            raise ValueError('Material bounds must be nonempty')
        if e.material_before != e.material_after or e.anchor_bounds != b:
            raise ValueError('Anchor selection must retain independent material bounds/geometry')
        immutable = ['number', 'view_type', 'source', 'source_sha256', 'matrix',
                     'scale', 'x', 'y', 'angle', 'unfold']
        if any(getattr(e.before_annotations, key) != getattr(e.final_whole, key) for key in immutable):
            raise ValueError('Immutable source/type/matrix/pose changed')
        if not e.writeback_complete_epoch < e.final_recapture_epoch:
            raise ValueError('Final whole annotated bounds must be recaptured after writeback')
        if len({c.open_id for c in e.saved_ro}) != 2:
            raise ValueError('Two distinct saved RO observations required')
        if not e.final_recapture_epoch < e.saved_ro[0].epoch < e.saved_ro[1].epoch:
            raise ValueError('Saved RO observations must follow final recapture')
        for cycle in e.saved_ro:
            if (not cycle.read_only or cycle.state != e.final_whole
                    or cycle.drawing_sha256 != e.sealed_drawing_sha256):
                raise ValueError('Final saved whole annotated view state did not persist')
    except (ValueError, ValidationError) as exc:
        return _result([str(exc)])
    return _result([])
